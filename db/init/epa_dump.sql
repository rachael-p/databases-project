CREATE DEFINER=`FA25_rpei2`@`%` PROCEDURE `AllPercentages`(IN password VARCHAR(15))
BEGIN
  IF EXISTS (SELECT 1 FROM Passwords WHERE curpasswords = password) THEN
    SELECT r.SSN, r.LName, r.FName, r.Section,
      ROUND(100 * r.hw1 / NULLIF(t.hw1, 0), 2) AS HW1,
      ROUND(100 * r.hw2a / NULLIF(t.hw2a, 0), 2) AS HW2a,
      ROUND(100 * r.hw2b / NULLIF(t.hw2b, 0), 2) AS HW2b,
      ROUND(100 * r.midterm / NULLIF(t.midterm, 0), 2) AS Midterm,
      ROUND(100 * r.hw3 / NULLIF(t.hw3, 0), 2) AS HW3,
      ROUND(100 * r.fexam / NULLIF(t.fexam, 0), 2) AS FExam,
      wpts.num AS WeightedAvg
    FROM Rawscores r, TotalPoints t, (
      SELECT s.SSN, ROUND(
        s.hw1 * w.hw1
        + s.hw2a * w.hw2a
        + s.hw2b * w.hw2b
        + s.midterm * w.midterm
        + s.hw3 * w.hw3
        + s.fexam * w.fexam, 3) AS num
      FROM Rawscores s, WtdPts w
      GROUP BY s.SSN) AS wpts
    WHERE r.SSN = wpts.SSN AND wpts.SSN <> 1 AND wpts.SSN <> 2
    ORDER BY section ASC, WeightedAvg DESC;
